"""Write THIRD_PARTY_LICENSES.md: every component the installed program ships, with its licence (NFR-LIC-2).

    uv run python scripts/third_party_licenses.py --out THIRD_PARTY_LICENSES.md

Python: the runtime dependencies of vision-station, followed recursively (not the dev or build groups).
Interface: the production packages of frontend/package-lock.json (dev packages are not in the build).
A licence that looks copyleft (GPL, AGPL, LGPL, SSPL) is listed at the top and makes the script fail, so
nothing like it ships by accident (NFR-LIC-1).
"""

import argparse
import json
import re
import sys
from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[1]
COPYLEFT = re.compile(r"\b(A?GPL|LGPL|SSPL|GNU (Affero |Lesser )?General Public)", re.I)
# PyInstaller's bootloader is GPL with an exception that allows closed programs (TD-15); it ships in the exe.
ALLOWED = {"pyinstaller"}


def _licence(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    expression = meta.get("License-Expression")
    if expression:
        return expression
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    if classifiers:
        return "; ".join(classifiers)
    text = (meta.get("License") or "").strip().splitlines()
    return text[0][:80] if text else "?"


def python_packages() -> list[tuple[str, str, str]]:
    seen: dict[str, tuple[str, str, str]] = {}
    pending: list[tuple[str, frozenset[str]]] = [("vision-station", frozenset({"uvc"}))]  # the C920 extra ships on Windows
    done: set[tuple[str, frozenset[str]]] = set()
    while pending:
        name, extras = pending.pop()
        key = re.sub(r"[-_.]+", "-", name).lower()
        if (key, extras) in done:
            continue
        done.add((key, extras))
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue
        seen[key] = (dist.metadata["Name"], dist.version, _licence(dist))
        for text in dist.requires or []:
            requirement = Requirement(text)
            wanted = requirement.marker is None or any(requirement.marker.evaluate({"extra": e}) for e in extras or {""})
            if wanted:
                pending.append((requirement.name, frozenset(requirement.extras)))
    seen.pop("vision-station", None)
    return sorted(seen.values(), key=lambda p: p[0].lower())


def npm_packages() -> list[tuple[str, str, str]]:
    lock = json.loads((ROOT / "frontend" / "package-lock.json").read_text(encoding="utf-8"))
    out = []
    for path, info in lock.get("packages", {}).items():
        if not path or info.get("dev") or info.get("devOptional") or info.get("optional"):
            continue
        out.append((path.split("node_modules/")[-1], info.get("version", ""), info.get("license", "?")))
    return sorted(out, key=lambda p: p[0].lower())


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=ROOT / "THIRD_PARTY_LICENSES.md")
    args = parser.parse_args()
    py, js = python_packages(), npm_packages()
    bad = [p for p in py + js if COPYLEFT.search(p[2]) and p[0].lower() not in ALLOWED]
    lines = ["# Third-party components", "", "Generated by scripts/third_party_licenses.py. Licences as the packages declare them.", ""]
    if bad:
        lines += ["## Needs review (copyleft-looking licence)", ""] + [f"- {n} {v}: {lic}" for n, v, lic in bad] + [""]
    for title, items in (("Program (Python)", py), ("Interface (JavaScript)", js)):
        lines += [f"## {title}", "", "| Package | Version | Licence |", "|---|---|---|"] + [f"| {n} | {v} | {lic} |" for n, v, lic in items] + [""]
    lines += ["## Bundled tools", "", "| Tool | Licence |", "|---|---|", "| PyInstaller bootloader | GPL-2.0 with the bootloader exception (closed programs allowed) |", "| WinSW (Windows service wrapper) | MIT |", ""]
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print(f"{args.out}: {len(py)} Python and {len(js)} JavaScript packages" + (f"; {len(bad)} need review" if bad else ""))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
